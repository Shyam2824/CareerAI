def normalize_skills(skills: str | None) -> set[str]:

    if not skills:
        return set()

    return {
        item.strip().lower()
        for item in skills.split(",")
        if item.strip()
    }


def personalize_roadmap(
    target_role: str,
    technical_skills: str | None,
    missing_skills: list[str] | None = None,
):

    roadmap = get_roadmap(target_role)

    user_skills = normalize_skills(
        technical_skills
    )

    missing = {
        item.strip().lower()
        for item in (missing_skills or [])
    }

    personalized = []

    for phase in roadmap:

        topics = []

        for topic in phase["topics"]:

            topic_lower = topic.lower()

            completed = (
                topic_lower in user_skills
                and topic_lower not in missing
            )

            topics.append(
                {
                    "name": topic,
                    "completed": completed,
                }
            )

        personalized.append(
            {
                "phase": phase["phase"],
                "title": phase["title"],
                "weeks": phase["weeks"],
                "topics": topics,
                "project": phase["project"],
            }
        )

    total_weeks = sum(
        phase["weeks"]
        for phase in personalized
    )

    return {
        "roadmap": personalized,
        "estimated_months": max(
            1,
            round(total_weeks / 4),
        ),
    }


def calculate_progress(
    roadmap: list,
    completed_topics: list[str],
):

    if not roadmap:
        return 0

    completed = {
        item.strip().lower()
        for item in completed_topics
    }

    total_topics = 0
    completed_count = 0

    for phase in roadmap:

        for topic in phase["topics"]:

            total_topics += 1

            if topic["name"].strip().lower() in completed:
                completed_count += 1

    if total_topics == 0:
        return 0

    return round(
        (completed_count / total_topics) * 100,
        2,
    )


